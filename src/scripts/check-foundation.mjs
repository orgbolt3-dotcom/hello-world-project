const missing = [];
for (const file of requiredFiles) {
  try {
    await access(resolve(file));
  } catch {
    missing.push(file);
  }
}

let knowledgeError;
try {
  const knowledge = JSON.parse(await readFile(resolve("src/data/knowledge.json"), "utf8"));
  if (!Array.isArray(knowledge.entries) || knowledge.entries.length < 50) {
    knowledgeError = "knowledge.json must contain at least 50 entries.";
  }
} catch {
  knowledgeError = "knowledge.json must be valid JSON.";
}

if (missing.length || knowledgeError) {
  if (missing.length) console.error(`Missing foundation files:\n${missing.join("\n")}`);
  if (knowledgeError) console.error(knowledgeError);
  process.exitCode = 1;
} else {
  console.log("Foundation check passed: required files and local knowledge are present.");
}
